//! Cross-version wire-compatibility guard for the loro upgrade.
//!
//! The whole workspace moves to a single loro version atomically, so we cannot
//! link two loro versions in one binary to test interop directly. Instead this
//! suite freezes a `.loro` snapshot captured under the PRIOR loro version
//! (1.10.3) as embedded bytes and decodes it under the CURRENT version. If a
//! loro upgrade ever silently changed the snapshot encoding, this test fails —
//! which would mean existing on-disk `.loro` files across the fleet are no
//! longer readable, the single risk that matters for this upgrade.
//!
//! The fixture was captured once on the 1.10.3 build via a throwaway
//! `examples/capture_loro_fixture.rs` from:
//!   `NoteDocument::from_markdown("note.md", FIXTURE_MARKDOWN, author(1))`
//!   then `export_snapshot()` and `version().encode()`.
//! Re-capture it (and update the constants) only if the wire format is
//! deliberately changed AND `CURRENT_SYNC_VERSION` is bumped accordingly.

use sync_core::{NoteDocument, PeerId};

fn author(n: u8) -> PeerId {
    PeerId::from_bytes([n; 32])
}

/// The markdown the frozen snapshot was built from (frontmatter + heading + body).
const FIXTURE_MARKDOWN: &str = "---\ntitle: T\n---\n\n# H\n\nbody";

