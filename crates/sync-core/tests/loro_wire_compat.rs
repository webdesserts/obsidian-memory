/// `version().encode()` of the same document captured under loro 1.10.3.
#[rustfmt::skip]
const FIXTURE_VERSION_VECTOR: &[u8] = &[
    0x01, 0xc5, 0xe3, 0xbe, 0xa7, 0xbf, 0x8a, 0xe6, 0xef, 0x38, 0x18,
];

/// A `.loro` snapshot written by the prior loro version must decode to the exact
/// same content and version vector under the current version. This is the "old
/// bytes read by new code" proof — the guarantee that an upgrade does not strand
/// existing on-disk documents across the fleet.
#[test]
fn frozen_1_10_3_snapshot_decodes_unchanged() {
    let doc = NoteDocument::from_bytes("note.md", FIXTURE_SNAPSHOT, author(2))
        .expect("a 1.10.3 snapshot must still import under the current loro");

    assert_eq!(
        doc.to_markdown(),
        FIXTURE_MARKDOWN,
        "content of a frozen 1.10.3 snapshot must be byte-identical after upgrade"
    );

    let expected_vv = loro::VersionVector::decode(FIXTURE_VERSION_VECTOR)
        .expect("the frozen version-vector bytes must decode");
    assert_eq!(
        doc.version(),
        expected_vv,
        "version vector of a frozen 1.10.3 snapshot must be unchanged after upgrade"
    );
}

/// Forward-compat smoke: a snapshot exported by the CURRENT loro re-imports to
/// identical content and version vector. Guards that the export/import round-trip
/// did not silently change shape in the upgrade (independent of the frozen
/// fixture, which only proves the read direction).
#[test]
fn current_version_snapshot_round_trips() {
    let original = NoteDocument::from_markdown("note.md", FIXTURE_MARKDOWN, author(1))
        .expect("from_markdown must build a document");
    let snapshot = original.export_snapshot().expect("export must succeed");

    let reimported = NoteDocument::from_bytes("note.md", &snapshot, author(2))
        .expect("a freshly-exported snapshot must re-import");

    assert_eq!(
        reimported.to_markdown(),
        original.to_markdown(),
        "a current-version snapshot must round-trip its content"
    );
    assert_eq!(
        reimported.version(),
        original.version(),
        "a current-version snapshot must round-trip its version vector"
    );
}
